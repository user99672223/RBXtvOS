#!/usr/bin/env python3
"""Phase 1: inventory the unpacked bundle.

Writes:
  evidence/inventory.json   machine-readable
  evidence/inventory.md     human-readable (Mach-Os, Info.plist keys, extensions, entitlements)
Usage: scripts/01_inventory.py  (expects work/unpacked from scripts/01_unpack.sh)
"""
import json
import plistlib
import sys

sys.path.insert(0, __import__("os").path.dirname(__file__))
from lib_macho import (EVIDENCE, app_dir, build_version, encryption, entitlements, find_machos,
                       libraries, parse, rel)

PLIST_KEYS = ["CFBundleIdentifier", "CFBundleShortVersionString", "CFBundleVersion", "CFBundleExecutable",
              "MinimumOSVersion", "UIDeviceFamily", "CFBundleSupportedPlatforms", "DTPlatformName",
              "DTPlatformVersion", "DTPlatformBuild", "DTSDKName", "DTSDKBuild", "DTXcode", "DTXcodeBuild",
              "DTCompiler", "UIRequiredDeviceCapabilities", "LSRequiresIPhoneOS"]


def main():
    app = app_dir()
    inv = {"app": app.name, "machos": [], "plists": {}, "extensions": [], "entitlements": {}}
    for p in find_machos(app):
        r = rel(p, app)
        slices = []
        for b in parse(p):
            slices.append({
                "cpu": str(b.header.cpu_type).split(".")[-1],
                "subtype": int(b.header.cpu_subtype),
                "filetype": str(b.header.file_type).split(".")[-1],
                "build_version": build_version(b),
                "cryptid": encryption(b),
                "has_code_signature": b.has_code_signature,
                "libraries": libraries(b),
            })
        inv["machos"].append({"path": r, "size": p.stat().st_size, "slices": slices})
        ent = entitlements(p)
        if ent is not None:
            inv["entitlements"][r] = ent
    for pl in sorted(app.rglob("Info.plist")):
        try:
            d = plistlib.loads(pl.read_bytes())
        except Exception as e:  # noqa
            continue
        inv["plists"][rel(pl, app)] = {k: d.get(k) for k in PLIST_KEYS if k in d}
        if "NSExtension" in d:
            ext = d["NSExtension"]
            inv["extensions"].append({"path": rel(pl.parent, app),
                                      "NSExtensionPointIdentifier": ext.get("NSExtensionPointIdentifier"),
                                      "NSExtensionPrincipalClass": ext.get("NSExtensionPrincipalClass"),
                                      "keys": sorted(ext.keys())})
    main_pl = plistlib.loads((app / "Info.plist").read_bytes())
    inv["main_plist_all_keys"] = sorted(main_pl.keys())

    EVIDENCE.mkdir(exist_ok=True)
    (EVIDENCE / "inventory.json").write_text(json.dumps(inv, indent=1, default=str, sort_keys=True))

    md = ["# Bundle inventory (generated by scripts/01_inventory.py)", ""]
    md += ["## Mach-O files", "", "| Path | Size | CPU | Type | Platform | minOS | SDK | cryptid | signed |",
           "|---|---|---|---|---|---|---|---|---|"]
    for m in inv["machos"]:
        for s in m["slices"]:
            bv = s["build_version"] or {}
            md.append(f"| `{m['path']}` | {m['size']:,} | {s['cpu']} ({s['subtype']}) | {s['filetype']} | "
                      f"{bv.get('platform')} | {bv.get('minos')} | {bv.get('sdk')} | {s['cryptid']} | "
                      f"{s['has_code_signature']} |")
    md += ["", "## Linked libraries per Mach-O", ""]
    for m in inv["machos"]:
        md.append(f"### `{m['path']}`")
        for lib in m["slices"][0]["libraries"]:
            md.append(f"- `{lib['name']}` ({lib['kind']})")
        md.append("")
    md += ["## Info.plist platform keys", ""]
    for k, v in inv["plists"].items():
        md.append(f"### `{k}`")
        md.append("```json\n" + json.dumps(v, indent=1, default=str) + "\n```")
    md += ["", "## App extensions", ""]
    for e in inv["extensions"]:
        md.append(f"- `{e['path']}`: `{e['NSExtensionPointIdentifier']}` (principal `{e['NSExtensionPrincipalClass']}`)")
    md += ["", "## Original entitlements (from embedded code signatures)", ""]
    for k, v in inv["entitlements"].items():
        md.append(f"### `{k}`")
        md.append("```json\n" + json.dumps(v, indent=1, default=str, sort_keys=True) + "\n```")
    (EVIDENCE / "inventory.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
