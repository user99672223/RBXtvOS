#!/usr/bin/env python3
"""Phase 3: generate evidence/shims.md, one entry per missing item.

CLAUDE.md fixes the shape of each entry and requires it to exist *before* the
shim is written. The entries are generated rather than hand-written so they
cannot drift from the evidence they cite: every field is joined from
missing.json, the device/SDK export lists, the iOS SDK contracts and the
per-shim decisions in shim/decisions.json.

The one hand-maintained input is shim/decisions.json: the decision
(STUB / REIMPLEMENT / REDIRECT), its reason and its status. Everything else
comes from the collected evidence.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from lib_macho import EVIDENCE, ROOT  # noqa: E402

DECISIONS = ROOT / "shim" / "decisions.json"
MISSING = EVIDENCE / "missing.json"
EXPORTS = EVIDENCE / "exports"
SDK = EVIDENCE / "sdk"

CLASS_PREFIX = "_OBJC_CLASS_$_"
METACLASS_PREFIX = "_OBJC_METACLASS_$_"


def sources():
    cfg = EVIDENCE / "queries" / "evidence_sources.json"
    return json.loads(cfg.read_text()) if cfg.is_file() else {}


def main():
    if not MISSING.is_file():
        raise SystemExit(f"{MISSING} is missing; run scripts/02_missing.py first")
    if not DECISIONS.is_file():
        raise SystemExit(f"{DECISIONS} is missing; it carries the per-item decisions")

    missing = json.loads(MISSING.read_text())
    decisions = json.loads(DECISIONS.read_text())
    src = sources()

    dev_label = src.get("device", "")
    tvos_label = src.get("tvos_sdk", "")
    ios_label = src.get("ios_sdk", "")

    # iOS SDK class contracts, for the Contract line
    contracts = {}
    for f in SDK.glob("*_class_contracts.json"):
        contracts.update(json.loads(f.read_text()))
    ios_targets = {}
    for f in SDK.glob("ios*_header_targets.json"):
        ios_targets.update(json.loads(f.read_text()))

    # device library presence, for the "missing on device" line
    dev_libs = {}
    p = SDK / f"{dev_label}_libraries.json"
    if p.is_file():
        dev_libs = json.loads(p.read_text())
    tvos_libs = {}
    p = SDK / f"{tvos_label.replace('sdk_', '')}_libraries.json"
    if p.is_file():
        tvos_libs = json.loads(p.read_text())

    # group the missing symbols by library
    by_lib = defaultdict(list)
    for lib, syms in missing["missing_symbols"].items():
        for sym, binaries in syms.items():
            by_lib[lib].append((sym, binaries))

    L = []
    L.append("# Shim evidence log (Phase 3)\n")
    L.append("Generated by `scripts/03_shims_md.py`. One entry per missing item, in the\n"
             "shape CLAUDE.md Phase 3 defines. Every line but Decision / Reason / Status\n"
             "is joined from the collected evidence, so the log cannot drift from it;\n"
             "those three come from `shim/decisions.json`.\n")
    L.append("\n## Evidence sources used\n")
    L.append("| Source | Set | Notes |")
    L.append("|---|---|---|")
    prov = src.get("_provenance", {})
    L.append(f"| 1. device | `{dev_label}` | {prov.get('device','')} |")
    L.append(f"| 2. tvOS SDK | `{tvos_label}` | {prov.get('tvos_sdk','')} |")
    L.append(f"| 3. iOS SDK | `{ios_label}` | {prov.get('ios_sdk','')} |")
    L.append("| 5. dyld | `dyld-1378` | see `evidence/dyld_reexport.md` |")

    t = missing["totals"]
    L.append("\n## Totals\n")
    L.append(f"- imports that resolve on the device: **{t['resolved_ok']}**")
    L.append(f"- unresolved non-weak eager imports (launch blockers): **{t['missing_symbols']}**")
    L.append(f"- libraries absent from the device: **{t['missing_frameworks']}**")
    L.append(f"- missing ObjC classes: **{t['missing_classes']}**")
    L.append(f"- weak-missing (dyld binds to NULL; app still loads): {t['weak_missing']}")
    L.append(f"- lazy-missing (bound on first call, not at launch): {t.get('lazy_missing', 0)}")
    L.append(f"- present on the device but absent from the tvOS SDK "
             f"(private on tvOS): {t['private_on_tvos']}")

    L.append("\n---\n")

    # ------------------------------------------------------------- per library
    for lib in sorted(set(list(by_lib) + list(decisions.get("libraries", {})))):
        entry = decisions.get("libraries", {}).get(lib)
        syms = sorted(by_lib.get(lib, []))
        short = lib.rstrip("/").split("/")[-1]
        L.append(f"\n### {short}\n")
        L.append(f"`{lib}`\n")

        importers = sorted({b for _s, bins in syms for b in bins})
        if entry and entry.get("imported_by"):
            importers = entry["imported_by"]
        L.append(f"- **Imported by:** {', '.join('`'+b+'`' for b in importers) or '—'}")

        # missing-on-device evidence
        dev = dev_libs.get(lib)
        tv = tvos_libs.get(lib)
        bits = []
        if dev is not None:
            if dev.get("present_in_cache"):
                bits.append(f"present in the device cache (`{dev_label}`) with "
                            f"{dev.get('exports','?')} exported names, but it does not "
                            f"export the symbol(s) below")
            else:
                bits.append(f"**absent from the device cache** (`{dev_label}`)")
        if tv is not None:
            bits.append("exported by tvOS SDK's .tbd" if tv.get("present")
                        else "**absent from the tvOS SDK**")
        if entry and entry.get("missing_evidence"):
            bits.append(entry["missing_evidence"])
        L.append(f"- **Missing on device — evidence:** {'; '.join(bits) or 'see missing.json'}")

        # contract
        contract_lines = []
        for sym, _bins in syms:
            if sym.startswith(CLASS_PREFIX):
                cls = sym[len(CLASS_PREFIX):]
                c = contracts.get(cls, {})
                iface = c.get("interface")
                if iface:
                    contract_lines.append(
                        f"`{cls}`: `{iface['decl']}` — superclass `{iface['superclass']}`"
                        f", protocols {iface['protocols'] or 'none'} "
                        f"({ios_label} `{iface['header']}`:{iface['line']})")
                else:
                    tgt = ios_targets.get(f"{cls}-decl")
                    if tgt and tgt.get("hits"):
                        h = tgt["hits"][0]
                        contract_lines.append(
                            f"`{cls}`: {ios_label} `{h['header']}`:{h['line']}")
        if entry and entry.get("contract"):
            contract_lines.append(entry["contract"])
        L.append(f"- **Contract — evidence:** "
                 + ("; ".join(contract_lines) if contract_lines
                    else f"see `evidence/sdk/{ios_label.replace('sdk_','')}_*` "))

        # referenced selectors
        if entry and entry.get("selectors"):
            L.append(f"- **Referenced selectors / call sites:** "
                     + ", ".join(f"`{s}`" for s in entry["selectors"]))
        else:
            L.append("- **Referenced selectors / call sites:** none found in "
                     "`__objc_selrefs` (symbol is referenced, no selector is)")

        L.append(f"- **Decision:** {entry['decision'] if entry else 'UNDECIDED'}")
        L.append(f"- **Reason:** {entry['reason'] if entry else '—'}")
        L.append(f"- **Status:** {entry.get('status','UNTESTED') if entry else 'UNTESTED'}")
        if entry and entry.get("shim"):
            L.append(f"- **Shim:** `{entry['shim']}` "
                     f"({entry.get('kind','?')}), source `{entry.get('source','?')}`")

        if syms:
            L.append("\n  Symbols:\n")
            for sym, bins in syms:
                L.append(f"  - `{sym}` ← {', '.join(bins)}")

    # --------------------------------------------------- non-symbol blockers
    extra = decisions.get("load_command_only", {})
    if extra:
        L.append("\n---\n")
        L.append("\n## Load-command-only blockers (no missing symbols)\n")
        L.append("These have **no unresolved symbols at all** and so never appeared in\n"
                 "`missing.json`. Roblox links each with a non-weak `LC_LOAD_DYLIB` while\n"
                 "importing nothing from it, and dyld requires such a library to be\n"
                 "loadable regardless, so each would fail the launch before any Roblox\n"
                 "code ran. `scripts/05_verify.py` checks load commands separately from\n"
                 "symbols for exactly this reason.\n")
        for lib, e in sorted(extra.items()):
            L.append(f"\n### {lib.rstrip('/').split('/')[-1]}\n")
            L.append(f"`{lib}`\n")
            L.append(f"- **Imported by:** {', '.join('`'+b+'`' for b in e['imported_by'])}")
            L.append(f"- **Missing on device — evidence:** {e['missing_evidence']}")
            L.append(f"- **Symbols imported:** {e.get('symbols_imported', 0)}")
            L.append(f"- **Decision:** {e['decision']}")
            L.append(f"- **Reason:** {e['reason']}")
            L.append(f"- **Status:** {e.get('status','UNTESTED')}")
            L.append(f"- **Shim:** `{e['shim']}`")

    # ------------------------------------------------- lazy, deliberately unshimmed
    lazy = decisions.get("lazy_not_shimmed", {})
    if lazy:
        L.append("\n---\n")
        L.append("\n## Missing but lazily bound (deliberately not shimmed)\n")
        L.append("dyld does not resolve a lazy binding at launch, so these cannot stop\n"
                 "the app loading; it binds them on first call. Shimming them would add\n"
                 "behaviour the iOS build does not have, so each is recorded with the\n"
                 "reason it is left alone.\n")
        for lib, e in sorted(lazy.items()):
            L.append(f"\n### {lib.rstrip('/').split('/')[-1]}\n")
            L.append(f"`{lib}`\n")
            L.append(f"- **Imported by:** {', '.join('`'+b+'`' for b in e['imported_by'])}")
            L.append(f"- **Missing on device — evidence:** {e['missing_evidence']}")
            L.append(f"- **Decision:** {e['decision']}")
            L.append(f"- **Reason:** {e['reason']}")
            L.append(f"- **Status:** {e.get('status','UNTESTED')}")
            L.append("\n  Symbols:\n")
            for s in e["symbols"]:
                L.append(f"  - `{s}`")

    # ---------------------------------------------------------------- our code
    ours = decisions.get("our_code", {})
    if ours:
        L.append("\n---\n")
        L.append("\n## Our own components (not shims for missing API)\n")
        for name, e in sorted(ours.items()):
            L.append(f"\n### {name}\n")
            L.append(f"- **What:** {e['what']}")
            L.append(f"- **Evidence:** {e['evidence']}")
            L.append(f"- **Decision:** {e['decision']}")
            L.append(f"- **Reason:** {e['reason']}")
            L.append(f"- **Status:** {e.get('status','UNTESTED')}")
            if e.get("private_api"):
                L.append(f"- **Private API used:** {e['private_api']}")

    out = EVIDENCE / "shims.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out} ({len(L)} lines)")
    known = set(decisions.get("libraries", {})) | set(decisions.get("lazy_not_shimmed", {}))
    undecided = [lib for lib in by_lib if lib not in known]
    if undecided:
        print(f"\n{len(undecided)} libraries have missing symbols but no decision entry:")
        for lib in undecided:
            print("   ", lib)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
